void UDespawnSubsystem::Despawn(AActor* const Actor)
{
	if (!IsValid(Actor))
	{
		return;
	}

	UWorld* const World = Actor->GetWorld();
	if (UDespawnSubsystem* const Subsystem = World ? World->GetSubsystem<UDespawnSubsystem>() : nullptr)
	{
		Subsystem->DespawnNow(*Actor);
		return;
	}

	// No subsystem (an editor world, for example): nothing can be pooled there.
	Actor->Destroy();
}

void UDespawnSubsystem::DespawnNow(AActor& Actor)
{
	UWorld* const World = GetWorld();
	USectorDirectorSubsystem* const Director = World ? World->GetSubsystem<USectorDirectorSubsystem>() : nullptr;

	// 1. Generated by the sector: the plugin releases it and remembers the removal if its spawn entry says so.
	if (Director && Director->ConsumeSpawnedActor(&Actor))
	{
		return;
	}

	// 2. Taken from the pool by this subsystem (dropped loot): straight back to the pool.
	if (RemoveDroppedLoot(Actor))
	{
		if (UActorPoolSubsystem* const Pool = World ? World->GetSubsystem<UActorPoolSubsystem>() : nullptr)
		{
			Pool->Release(&Actor);
		}
		return;
	}

	// The director refuses ConsumeSpawnedActor while it regenerates, so a sector actor would fall through to Destroy.
	// Try again next frame instead. Bound to the actor, so the pool's teardown release clears the retry.
	if (Director && Director->IsBusy() && World)
	{
		const TWeakObjectPtr<AActor> WeakActor = &Actor;
		World->GetTimerManager().SetTimerForNextTick(FTimerDelegate::CreateWeakLambda(&Actor, [WeakActor]()
		{
			Despawn(WeakActor.Get());
		}));
		return;
	}

	// 3. Hand-placed or spawned by a level spawner: never came from the pool.
	Actor.Destroy();
}

ALootPickup* UDespawnSubsystem::DropLoot(const TSubclassOf<ALootPickup> PickupClass, const FVector& Location,
	const FLootBundle& Bundle, const float Lifespan)
{
	UWorld* const World = GetWorld();
	UActorPoolSubsystem* const Pool = World ? World->GetSubsystem<UActorPoolSubsystem>() : nullptr;
	if (!Pool || !PickupClass || Bundle.IsEmpty())
	{
		return nullptr;
	}

	ALootPickup* const Pickup = Cast<ALootPickup>(Pool->Acquire(PickupClass, FTransform(Location)));
	if (!Pickup)
	{
		return nullptr;
	}

	// Tracked before it is filled: filling it can collect it at once, and that despawn must find it here.
	RemoveDroppedLoot(*Pickup);
	DroppedLoot.Add(Pickup);

	Pickup->SetContents(Bundle);

	const bool bStillDropped = DroppedLoot.ContainsByPredicate([Pickup](const TWeakObjectPtr<ALootPickup>& Entry)
	{
		return Entry.Get() == Pickup;
	});
	if (!bStillDropped)
	{
		return nullptr;
	}

	if (Lifespan > 0.f)
	{
		Pickup->StartDespawnTimer(Lifespan);
	}
	return Pickup;
}

ALootPickup* UDespawnSubsystem::DropDeathLoot(const TSubclassOf<ALootPickup> PickupClass, const FVector& Location,
	const FLootBundle& Bundle, const float Lifetime)
{
	ALootPickup* const Pickup = DropLoot(PickupClass, Location, Bundle, Lifetime);
	if (!Pickup)
	{
		return nullptr;
	}

	const UWorld* const World = GetWorld();
	const USectorDirectorSubsystem* const Director = World ? World->GetSubsystem<USectorDirectorSubsystem>() : nullptr;

	FDeathLootRecord& Record = DeathLoot.AddDefaulted_GetRef();
	Record.Pickup = Pickup;
	Record.PickupClass = PickupClass;
	Record.SectorId = Director ? Director->GetCurrentSectorId() : NAME_None;
	Record.ExpiryTime = Lifetime > 0.f ? GetNow() + Lifetime : -1.0;

	ShowDeathCargoMarker(*Pickup, Record.ExpiryTime);
	return Pickup;
}

void UDespawnSubsystem::ReleaseAllDroppedLoot()
{
	UWorld* const World = GetWorld();
	UActorPoolSubsystem* const Pool = World ? World->GetSubsystem<UActorPoolSubsystem>() : nullptr;

	// Moved out first, so the list is empty however releasing a pickup reacts.
	const TArray<TWeakObjectPtr<ALootPickup>> ToRelease = MoveTemp(DroppedLoot);
	DroppedLoot.Reset();

	if (!Pool)
	{
		return;
	}

	for (const TWeakObjectPtr<ALootPickup>& Entry : ToRelease)
	{
		if (ALootPickup* const Pickup = Entry.Get())
		{
			Pool->Release(Pickup);
		}
	}
}

bool UDespawnSubsystem::RemoveDroppedLoot(const AActor& Actor)
{
	bool bFound = false;
	DroppedLoot.RemoveAllSwap([&Actor, &bFound](const TWeakObjectPtr<ALootPickup>& Entry)
	{
		const bool bMatch = Entry.Get() == &Actor;
		bFound |= bMatch;
		return bMatch || !Entry.IsValid();
	});

	// Death cargo that leaves play here was collected or timed out, so it is gone for good.
	DeathLoot.RemoveAll([&Actor](const FDeathLootRecord& Record)
	{
		ALootPickup* const Pickup = Record.Pickup.Get();
		if (Pickup != &Actor)
		{
			return false;
		}
		HideDeathCargoMarker(*Pickup);
		return true;
	});
	return bFound;
}

void UDespawnSubsystem::StoreDeathLootInPlay()
{
	for (FDeathLootRecord& Record : DeathLoot)
	{
		ALootPickup* const Pickup = Record.Pickup.Get();
		if (!Pickup)
		{
			continue;
		}

		// Stored on warp: off the HUD until its sector is ready again.
		HideDeathCargoMarker(*Pickup);

		// Whatever is left after partial collection, where it is now.
		Record.Contents = Pickup->GetContents();
		Record.Location = Pickup->GetActorLocation();
		Record.Pickup.Reset();
	}
}

void UDespawnSubsystem::RestoreDeathLoot(const FName SectorId)
{
	// Taken out first: DropLoot can collect a pickup at once, and that despawn edits DeathLoot.
	TArray<FDeathLootRecord> ToRestore;
	for (int32 Index = DeathLoot.Num() - 1; Index >= 0; --Index)
	{
		const FDeathLootRecord& Record = DeathLoot[Index];
		if (Record.Pickup.IsExplicitlyNull() && Record.SectorId == SectorId)
		{
			ToRestore.Add(Record);
			DeathLoot.RemoveAt(Index);
		}
	}

	const double Now = GetNow();
	for (FDeathLootRecord& Record : ToRestore)
	{
		if (Record.IsExpired(Now))
		{
			continue;
		}

		// The time it has left, so the expiry stays 'Lifetime after the death' however long the player was away.
		const float Remaining = Record.ExpiryTime >= 0.0 ? static_cast<float>(Record.ExpiryTime - Now) : 0.f;

		ALootPickup* const Pickup = DropLoot(Record.PickupClass, Record.Location, Record.Contents, Remaining);
		if (!Pickup)
		{
			// Empty, or collected the moment it appeared.
			continue;
		}

		Record.Pickup = Pickup;
		Record.Contents = FLootBundle();
		ShowDeathCargoMarker(*Pickup, Record.ExpiryTime);
		DeathLoot.Add(MoveTemp(Record));
	}
}

void UDespawnSubsystem::PruneDeathLoot()
{
	const double Now = GetNow();
	DeathLoot.RemoveAll([Now](const FDeathLootRecord& Record)
	{
		// Stale: the pickup was destroyed. A pickup in play with its time up is left to its own despawn timer.
		return Record.Pickup.IsStale() || (Record.Pickup.IsExplicitlyNull() && Record.IsExpired(Now));
	});
}

void UDespawnSubsystem::ShowDeathCargoMarker(ALootPickup& Pickup, const double ExpiryTime)
{
	UMapMarkerComponent* Marker = Pickup.FindComponentByClass<UMapMarkerComponent>();
	if (!Marker)
	{
		USceneComponent* const Root = Pickup.GetRootComponent();
		if (!Root)
		{
			return;
		}

		// Registering the component on a pickup in play runs its BeginPlay, which registers the marker.
		Marker = NewObject<UMapMarkerComponent>(&Pickup, TEXT("DeathCargoMarker"), RF_Transient);
		Marker->Label = NSLOCTEXT("DeathCargo", "MarkerLabel", "Lost cargo");
		Marker->SetupAttachment(Root);
		Pickup.AddInstanceComponent(Marker);
		Marker->RegisterComponent();
	}

	Marker->Type = EMapMarkerType::DroppedCargo;
	Marker->bShowScreenMarker = true;
	Marker->SetMarkerEnabled(true);
	Marker->SetExpiryTime(ExpiryTime);
	Marker->RegisterMarker();

	STARTECH_HUD_LOG(TEXT("Death cargo marker registered on %s, %s"), *Pickup.GetName(),
		ExpiryTime >= 0.0 ? *FString::Printf(TEXT("expires in %.0f s"), Marker->GetSecondsRemaining()) : TEXT("no expiry"));
}

void UDespawnSubsystem::HideDeathCargoMarker(ALootPickup& Pickup)
{
	UMapMarkerComponent* const Marker = Pickup.FindComponentByClass<UMapMarkerComponent>();
	if (!Marker)
	{
		return;
	}

	Marker->UnregisterMarker();
	Marker->SetExpiryTime(-1.0);
	STARTECH_HUD_LOG(TEXT("Death cargo marker unregistered on %s"), *Pickup.GetName());
}

double UDespawnSubsystem::GetNow() const
{
	const UWorld* const World = GetWorld();
	return World ? World->GetTimeSeconds() : 0.0;
}

void UDespawnSubsystem::OnWorldBeginPlay(UWorld& InWorld)
{
	Super::OnWorldBeginPlay(InWorld);

	if (USectorDirectorSubsystem* const Director = InWorld.GetSubsystem<USectorDirectorSubsystem>())
	{
		Director->OnSectorTransitionStarted.AddUniqueDynamic(this, &UDespawnSubsystem::HandleSectorTransitionStarted);
		Director->OnSectorReady.AddUniqueDynamic(this, &UDespawnSubsystem::HandleSectorReady);
		BoundDirector = Director;
	}
}

void UDespawnSubsystem::Deinitialize()
{
	if (USectorDirectorSubsystem* const Director = BoundDirector.Get())
	{
		Director->OnSectorTransitionStarted.RemoveDynamic(this, &UDespawnSubsystem::HandleSectorTransitionStarted);
		Director->OnSectorReady.RemoveDynamic(this, &UDespawnSubsystem::HandleSectorReady);
	}
	BoundDirector.Reset();
	DroppedLoot.Reset();
	DeathLoot.Reset();

	Super::Deinitialize();
}

bool UDespawnSubsystem::DoesSupportWorldType(const EWorldType::Type WorldType) const
{
	return WorldType == EWorldType::Game || WorldType == EWorldType::PIE;
}

void UDespawnSubsystem::HandleSectorTransitionStarted(const FName FromSectorId, const FName ToSectorId)
{
	// Death cargo is remembered first: ReleaseAllDroppedLoot empties the pickups it reads from.
	StoreDeathLootInPlay();
	PruneDeathLoot();

	// Dropped loot belongs to no sector, so it would otherwise follow the player into the next one.
	ReleaseAllDroppedLoot();
}

void UDespawnSubsystem::HandleSectorReady(const FName SectorId)
{
	PruneDeathLoot();
	RestoreDeathLoot(SectorId);
}
